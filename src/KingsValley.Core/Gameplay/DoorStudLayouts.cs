namespace KingsValley.Core.Gameplay;

/// <summary>
/// Positions of the exit door studs (table 0xB9AD of bank 13 of the MSX2 ROM), by total soul stones
/// of the stage. Each byte: x = (b &amp; 3) * 8, y = ((b &gt;&gt; 2) &amp; 3) * 8 inside the 32x32 door;
/// the game draws the first N, where N = the stones still missing.
/// </summary>
public static class DoorStudLayouts
{
    private static readonly byte[][] Layouts =
    {
        new byte[] { 0x5 },
        new byte[] { 0xA, 0x5 },
        new byte[] { 0x6, 0xA, 0x5 },
        new byte[] { 0xA, 0x5, 0xF, 0x0 },
        new byte[] { 0x3, 0xA, 0x5, 0xF, 0x0 },
        new byte[] { 0x9, 0x6, 0xA, 0x5, 0xC, 0x3 },
        new byte[] { 0x0, 0x9, 0x6, 0xA, 0x5, 0xC, 0x3 },
        new byte[] { 0xA, 0x5, 0x9, 0x6, 0xC, 0x3, 0xF, 0x0 },
        new byte[] { 0x1, 0xA, 0x5, 0x9, 0x6, 0xC, 0x3, 0xF, 0x0 },
        new byte[] { 0xA, 0x5, 0x0, 0xF, 0x4, 0xB, 0x8, 0x7, 0xC, 0x3 },
        new byte[] { 0x1, 0xA, 0x5, 0x0, 0xF, 0x4, 0xB, 0x8, 0x7, 0xC, 0x3 },
        new byte[] { 0x4, 0xB, 0x2, 0xD, 0x7, 0x8, 0xE, 0x1, 0xC, 0x3, 0xF, 0x0 },
        new byte[] { 0x5, 0x4, 0xB, 0x2, 0xD, 0x7, 0x8, 0xE, 0x1, 0xC, 0x3, 0xF, 0x0 },
        new byte[] { 0x9, 0x6, 0x3, 0xC, 0xF, 0x0, 0x4, 0x8, 0xD, 0xE, 0xB, 0x7, 0x2, 0x1 },
        new byte[] { 0x5, 0x9, 0x6, 0x3, 0xC, 0xF, 0x0, 0x4, 0x8, 0xD, 0xE, 0xB, 0x7, 0x2, 0x1 },
        new byte[] { 0xC, 0x9, 0x6, 0x3, 0xF, 0xA, 0x5, 0x0, 0xE, 0xD, 0x2, 0x1, 0xB, 0x8, 0x7, 0x4 },
    };

    /// <summary>Layout for <paramref name="total"/> stones (empty if 0 or more than 16).</summary>
    public static byte[] For(int total) => total >= 1 && total <= Layouts.Length ? Layouts[total - 1] : Array.Empty<byte>();
}
